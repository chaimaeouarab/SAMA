String tr(String key, AppLang lang) {
  final v = _s[key];
  if (v == null) return key;
  return v[lang.index];
}

/// Fill "%s" placeholders in order.
String trf(String key, AppLang lang, List<Object> args) {
  var s = tr(key, lang);
  for (final a in args) {
    s = s.replaceFirst('%s', '$a');
  }
  return s;
}

