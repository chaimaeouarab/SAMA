"""Audit the bundled NASA POWER data (assets/data/nasa_power.json).

  python scripts/audit_data.py                 # internal checks + statistics for every point
  python scripts/audit_data.py --online ids... # also re-download those points from NASA POWER and compare

Checks: season count, season boundaries (Oct 1 -> Sep 30 spans two calendar years), leap years, missing days,
outliers and physical bounds, agreement between the per-year rain table and the daily season series,
points that share one NASA grid cell, and per-point season rain statistics (mean/median/P10/P90/min/max).
Writes docs/DATA_AUDIT_RESULTS.md. Nothing here is a gauge comparison: POWER rain is satellite/reanalysis derived
and differs from rain gauges (see docs/DATA_AUDIT.md).
"""
import json
import statistics as st
import sys
import urllib.request
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
D = json.loads((ROOT / "assets/data/nasa_power.json").read_text(encoding="utf-8"))
POINTS = D["points"]
Y0, Y1 = D["years"]
report = []


def log(s=""):
    print(s)
    report.append(s)


def q(v, p):
    v = sorted(v)
    k = (len(v) - 1) * p
    lo, hi = int(k), min(int(k) + 1, len(v) - 1)
    return v[lo] + (v[hi] - v[lo]) * (k - lo)


def is_leap(y):
    return y % 4 == 0 and (y % 100 != 0 or y % 400 == 0)


def season_rain_from_seasons(seasons_rain, i):
    # Oct 1 .. May 31 of the season: 243 days, 244 if it contains Feb 29
    y = Y0 + i
    n = (date(y + 1, 6, 1) - date(y, 10, 1)).days
    return sum(v for v in seasons_rain[i][:n] if v > -990) / 10


def season_rain_from_years(rain, i):
    y = Y0 + i
    a, b = rain[str(y)], rain[str(y + 1)]
    return (sum(v for v in a[274:] if v > 0) + sum(v for v in b[:152] if v > 0)) / 10


problems = 0
log("# Data audit results (generated by scripts/audit_data.py)\n")
log(f"File fetched: {D.get('fetched')} · years {Y0}-{Y1} · {len(POINTS)} points\n")
log("| point | elev (m) | grid cell | missing days | seasons | rain mean | median | P10 | P90 | min | max | dry<250 |")
log("|---|---|---|---|---|---|---|---|---|---|---|---|")
cells = {}
sigs = {}
for pid, p in POINTS.items():
    s = p["seasons"]
    n = len(s["rain"])
    if n != Y1 - Y0:
        problems += 1
        log(f"PROBLEM {pid}: {n} seasons, expected {Y1 - Y0}")
    for i in range(n):
        y = Y0 + i
        expect_days = 366 if is_leap(y + 1) else 365  # Feb 29 of the following calendar year
        for var in s:
            if len(s[var][i]) != expect_days:
                problems += 1
                log(f"PROBLEM {pid} {var} season {y}-{y + 1}: {len(s[var][i])} days, expected {expect_days}")
    # physical bounds
    for var, lo, hi in [("rain", 0, 2500), ("tmax", -100, 560), ("tmin", -200, 400), ("rh", 0, 1000), ("ws", 0, 400), ("rad", 0, 400)]:
        bad = [v for ss in s[var] for v in ss if v > -990 and not (lo <= v <= hi)]
        if bad:
            problems += 1
            log(f"PROBLEM {pid} {var}: {len(bad)} values outside [{lo / 10},{hi / 10}] e.g. {bad[:3]}")
    # two independent paths must agree (daily series vs per-year table)
    for i in range(n):
        a, b = season_rain_from_seasons(s["rain"], i), season_rain_from_years(p["rain"], i)
        if abs(a - b) > 0.15:
            problems += 1
            log(f"PROBLEM {pid} season {Y0 + i}: daily series {a:.1f} mm vs yearly table {b:.1f} mm")
    rains = [season_rain_from_seasons(s["rain"], i) for i in range(n)]
    miss = sum(p["coverage"].values())
    dry = sum(1 for r in rains if r < 250)
    log(f"| {pid} | {p['elev']:.0f} | {p['srcLat']:.2f}, {p['srcLon']:.2f} | {miss} | {n} | {st.mean(rains):.0f} | {st.median(rains):.0f} | "
        f"{q(rains, .1):.0f} | {q(rains, .9):.0f} | {min(rains):.0f} | {max(rains):.0f} | {dry} |")
    # POWER echoes the requested coordinates; the real cell is the MERRA-2 grid cell (0.5 x 0.625 deg)
    cell = (round(p["lat"] / 0.5) * 0.5, round((p["lon"] + 180) / 0.625) * 0.625 - 180)
    cells.setdefault(cell, []).append(pid)
    sig = tuple(rains)
    sigs.setdefault(sig, []).append(pid)

log("\n## Points that share one NASA grid cell (identical data)\n")
for k, ids in cells.items():
    if len(ids) > 1:
        log(f"- cell {k}: {', '.join(ids)}")

log("\n## Elevation caveat\n")
log("POWER returns the elevation of its grid cell, not of the town. Compare with the real town elevation before trusting "
    "pressure/ET0 at that point (docs/DATA_AUDIT.md).")


def fetch(lat, lon):
    url = ("https://power.larc.nasa.gov/api/temporal/daily/point?parameters=PRECTOTCORR,T2M_MAX,T2M_MIN,ALLSKY_SFC_SW_DWN"
           f"&community=AG&longitude={lon}&latitude={lat}&start={Y0}0101&end={Y1}1231&format=JSON")
    with urllib.request.urlopen(url, timeout=240) as r:
        return json.load(r)["properties"]["parameter"]


if "--online" in sys.argv:
    ids = [a for a in sys.argv[1:] if not a.startswith("--")] or ["boufakrane"]
    log("\n## Online re-download comparison\n")
    for pid in ids:
        p = POINTS[pid]
        par = fetch(p["lat"], p["lon"])
        diffs = 0
        total = 0
        for i in range(len(p["seasons"]["rain"])):
            day = date(Y0 + i, 10, 1)
            for j, v in enumerate(p["seasons"]["rain"][i]):
                key = (day + timedelta(days=j)).strftime("%Y%m%d")
                live = par["PRECTOTCORR"].get(key, -999)
                total += 1
                if (v <= -990) != (live <= -990) or (v > -990 and abs(v - round(live * 10)) > 1):
                    diffs += 1
        log(f"- {pid}: {total} daily rain values compared, {diffs} differ")
        problems += diffs

log(f"\nProblems found: {problems}")
(ROOT / "docs" / "DATA_AUDIT_RESULTS.md").write_text("\n".join(report) + "\n", encoding="utf-8")
sys.exit(1 if problems else 0)
